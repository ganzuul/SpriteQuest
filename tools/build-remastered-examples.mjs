import { mkdir, writeFile } from 'node:fs/promises';
import { FIXTURES, TEXT_FIXTURES } from './remastered/fixtures.mjs';
import { foundations } from './remastered/foundations.mjs';
import { composition } from './remastered/composition.mjs';
import { advanced } from './remastered/advanced.mjs';
import { capstones } from './remastered/capstones.mjs';
const entries = [...foundations(), ...composition(), ...advanced(), ...capstones()];
await mkdir(new URL('../examples/remastered/', import.meta.url), { recursive: true });
for (const entry of entries) {
    const slug = entry.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/-$/, '');
    await writeFile(new URL(`../examples/remastered/${String(entry.number).padStart(2, '0')}-${slug}.lattice.json`, import.meta.url), JSON.stringify(entry.packages[0], null, 2) + '\n');
}
await writeFile(new URL('../src/workflow/remastered-example-data.js', import.meta.url), '// Generated by tools/build-remastered-examples.mjs.\nexport const REMASTERED_WORKFLOW_EXAMPLE_DATA = ' + JSON.stringify(entries, null, 2) + ';\n');
console.log(`Authored ${entries.length} remastered lessons.`);
await mkdir(new URL('../examples/remastered/fixtures/', import.meta.url), { recursive: true });
for (const [name, value] of Object.entries(FIXTURES))
    await writeFile(new URL('../examples/remastered/fixtures/' + name, import.meta.url), JSON.stringify(value, null, 2) + '\n');
for (const [name, value] of Object.entries(TEXT_FIXTURES))
    await writeFile(new URL('../examples/remastered/fixtures/' + name, import.meta.url), value);
