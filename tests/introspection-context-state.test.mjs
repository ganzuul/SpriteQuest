assert.equal(safeView.artifact.provenance.actorId,'actor');
const absentActor = await api.shapeContext({context:visibility},{mode:'perspective',actorId:'absent'});
assert.equal(absentActor.ok,true);
assert.deepEqual(absentActor.artifact.messages,[]);
assert.equal((await api.shapeContext({context:{kind:'context',messages:[{id:'bad',role:'user',text:'Bad',visibleTo:'actor'}]}},{mode:'perspective',actorId:'actor'})).ok,false);
let getterReads = 0;
const unsafeSettings = {mode:'focus',get targetTokens(){getterReads++;return 100;}};
assert.equal((await api.shapeContext({context:one},unsafeSettings,{countTokens})).ok,false);
assert.equal(getterReads,0);
const unsafeContext = {kind:'context',messages:[{id:'bad',role:'user',text:'Text',get visibleTo(){getterReads++;return ['actor'];}}]};
assert.equal((await api.shapeContext({context:unsafeContext},{mode:'perspective',actorId:'actor'})).ok,false);
assert.equal(getterReads,0);
const record = (recordType,payload,sourceRefs=[]) => ({kind:'data',value:{schemaVersion:1,recordType,scope:{chatId:'chat',actorId:'actor'},store:{id:'store',version:4},sourceRefs,payload}});
const initial = {traits:[],beliefs:[],goals:[],relationships:[],conflicts:[],conditions:[],episodes:[],values:{anger:1,trust:0.2},curves:{emotion:{phase:'onset',value:1,elapsed:0}},tracks:{consequences:{eventIds:['past'],count:1}}};
