/** Unknown settings are deliberately omitted so coverage checks can expose missing copy. */
export function describeGuideControl(key, controlKey) {
    if (!getNodeGuide(key) || typeof controlKey !== 'string') return null;
    const own = controls[key];
    if (own && Object.hasOwn(own, controlKey)) return own[controlKey];
    return Object.hasOwn(supplementaryControls, controlKey) ? supplementaryControls[controlKey] : null;
}

/** @returns {import('./node-guide-content').NodeGuide | null} */
export function getNodeGuide(key) {
    return typeof key === 'string' && Object.hasOwn(guides, key) ? guides[key] : null;
}

/** Match display identity, keeping user-authored aliases out of the lookup. */
export function nodeGuideKey(node) {
    const key = node?.type === 'workflow' ? node.operation
        : node?.type === 'note' && node.commentFrame ? 'comment' : node?.type;
    return getNodeGuide(key)?.key ?? null;
}
